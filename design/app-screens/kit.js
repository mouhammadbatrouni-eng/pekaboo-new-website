function chrome({ active = "more" } = {}) {
  const lang = document.documentElement.lang;
  const nav = document.createElement("nav");
  nav.className = "nav";
  nav.innerHTML = ["feed", "class", "home", "messages", "more"]
    .map((k) => `<div class="tab${k === active ? " on" : ""}" data-tab="${k}"><svg viewBox="0 0 24 24">${ICONS[k]}</svg><span>${TAB_LABELS[lang][k]}</span></div>`)
    .join("");
  document.querySelector(".screen").appendChild(nav);
  document.querySelectorAll("[data-icon]").forEach((el) => (el.outerHTML = svg(el.dataset.icon, ("ic " + el.className).trim())));
}
